/**
 * Step 4: build the knowledge graph from the reconstructed landscape.yml.
 *
 * Two phases, after the directory-builder lift/transform split:
 *   1. lift      — SPARQL Anything (java) triplifies landscape.yml into the raw
 *                  facade-x model and dumps it verbatim (sparql/lift.sparql). No
 *                  interpretation.
 *   2. transform — CONSTRUCT queries (sparql/transform/*.sparql, run in order)
 *                  navigate that raw model and emit a clean RDF/SKOS graph,
 *                  reusing SKOS/DCT/schema.org with a tiny dstack: namespace.
 *
 * Output: data/graph/landscape.ttl (committed, never hand-edited) — named for
 * its content, which is still only the Landkarte; once later steps enrich it
 * beyond the Landkarte it becomes the broader dstack graph. The SPARQL Anything
 * jar is cached under data/scratch/tools/ (gitignored), downloaded on first
 * run. Needs java. Run: npm run graph
 */

import { storeFromTurtles, sparqlConstruct, storeToTurtle, addTurtleToStore, newStore } from "@foerderfunke/sem-ops-utils"
import { ROOT, UPSTREAM, RECONSTRUCTED, GRAPH, SCRATCH } from "./paths.js"
import { execFileSync } from "child_process"
import path from "path"
import fs from "fs"

const SA_VERSION = "v1.1.0"
const JAR = path.join(SCRATCH, "tools", "sparql-anything.jar")
const LIFT_QUERY = path.join(import.meta.dirname, "sparql", "lift.sparql")
const TRANSFORM_DIR = path.join(import.meta.dirname, "sparql", "transform")
const LANDSCAPE = path.join(RECONSTRUCTED, "landscape.yml")
const RAW = path.join(SCRATCH, "landscape-raw.ttl")
const OUT = path.join(GRAPH, "landscape.ttl")
const REPO = "https://codeberg.org/benjaminaaron/d-stack-kg"

const PREFIXES = {
    skos: "http://www.w3.org/2004/02/skos/core#",
    dct: "http://purl.org/dc/terms/",
    ds: "https://deutschland-stack.gov.de/id/",
    dstack: "https://deutschland-stack.gov.de/vocab#",
}

// SPARQL Anything is the lift tool (no npm package); downloaded once and cached
// in scratch (gitignored). After a SA_VERSION bump, delete the cached jar to refetch.
async function ensureJar() {
    if (fs.existsSync(JAR)) return
    const url = `https://github.com/SPARQL-Anything/sparql.anything/releases/download/${SA_VERSION}/sparql-anything-${SA_VERSION}.jar`
    console.log(`Downloading sparql-anything ${SA_VERSION} ...`)
    fs.mkdirSync(path.dirname(JAR), { recursive: true })
    const res = await fetch(url)
    if (!res.ok) throw new Error(`${url} -> HTTP ${res.status}`)
    fs.writeFileSync(JAR, Buffer.from(await res.arrayBuffer()))
}

// Fail with a hint rather than a raw ENOENT.
try {
    execFileSync("java", ["-version"], { stdio: "ignore" })
} catch {
    console.error("java not found — SPARQL Anything needs a JRE (e.g. brew install openjdk)")
    process.exit(1)
}
if (!fs.existsSync(LANDSCAPE)) throw new Error(`missing ${path.relative(ROOT, LANDSCAPE)} — run step 2 (npm run reconstruct)`)

await ensureJar()

// Phase 1: lift landscape.yml -> raw facade-x TTL.
console.log("lift   data/reconstructed/landscape.yml -> facade-x")
fs.mkdirSync(SCRATCH, { recursive: true })
execFileSync("java", ["-jar", JAR, "-q", LIFT_QUERY,
    "-v", `location=${LANDSCAPE}`, "-f", "TTL", "-o", RAW], { stdio: ["ignore", "ignore", "inherit"] })

// Phase 2: transform it into the knowledge graph.
const raw = storeFromTurtles([fs.readFileSync(RAW, "utf8")])
const graph = newStore()
for (const f of fs.readdirSync(TRANSFORM_DIR).filter(f => f.endsWith(".sparql")).sort()) {
    const before = graph.size
    await sparqlConstruct(fs.readFileSync(path.join(TRANSFORM_DIR, f), "utf8"), [raw], graph)
    console.log(`transform ${f}: +${graph.size - before} triples`)
}

// Provenance & baseline disclaimer on the root scheme: where the snapshot came
// from and when, that this is an unofficial reconstruction, and a link to the
// repo that builds it (the project's first principle — provenance, not assertion).
const meta = JSON.parse(fs.readFileSync(path.join(UPSTREAM, "full.meta.json"), "utf8"))
const rootTripleAdditions = `
    @prefix ds:   <https://deutschland-stack.gov.de/id/> .
    @prefix dct:  <http://purl.org/dc/terms/> .
    @prefix rdfs: <http://www.w3.org/2000/01/rdf-schema#> .
    @prefix xsd:  <http://www.w3.org/2001/XMLSchema#> .
    ds:landkarte
        dct:source <${meta.source}> ;
        dct:date "${meta.retrievedAt.slice(0, 10)}"^^xsd:date ;
        rdfs:seeAlso <${REPO}> ;
        rdfs:comment "Unofficial prototype: the Tech-Stack Landkarte (an artifact of the Deutschland-Stack) as knowledge graph, reconstructed from the published full.json. Not an authoritative source; see the linked repository."@en .`
addTurtleToStore(graph, rootTripleAdditions)

fs.mkdirSync(GRAPH, { recursive: true })
fs.writeFileSync(OUT,
    "# The Tech-Stack-Landkarte modelled as RDF. Generated by step 4\n" +
    "# (npm run graph) from data/reconstructed/landscape.yml — not hand-edited.\n" +
    await storeToTurtle(graph, PREFIXES))
console.log(`OK: ${graph.size} triples -> data/graph/landscape.ttl`)
